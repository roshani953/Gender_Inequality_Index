if page == "Home":

    st.title("🌍 Gender Inequality Index Analysis")

    st.markdown(
        """
        Explore gender inequality across countries using
        data analysis, Principal Component Analysis (PCA),
        and K-Means clustering.
        """
    )

    st.markdown("---")

    col1, col2, col3, col4 = st.columns(4)

    col1.metric("Total Countries", len(df))

    col2.metric(
        "Total Indicators",
        len(features)
    )

    col3.metric(
        "Number of Clusters",
        2
    )

    col4.metric(
        "Silhouette Score",
        "0.4041"
    )

    st.markdown("---")

    st.subheader("Project Overview")

    st.write(
        """
        This project aims to identify groups of countries
        based on gender inequality indicators.

        The analysis considers reproductive health,
        education, political representation, labour force
        participation, and human development.
        """
    )

    st.subheader("Machine Learning Approach")

    col1, col2 = st.columns(2)

    with col1:
        st.info(
            """
            **Principal Component Analysis (PCA)**

            Used to reduce the dimensionality of the
            nine selected indicators while retaining
            approximately 90.49% of the variance.
            """
        )

    with col2:
        st.success(
            """
            **K-Means Clustering**

            Used to group countries into two clusters
            based on similarities in their indicators.
            """
        )

    st.subheader("Cluster Distribution")

    cluster_counts = (
        df['Cluster']
        .value_counts()
        .sort_index()
        .reset_index()
    )

    cluster_counts.columns = ['Cluster', 'Countries']

    fig = px.pie(
        cluster_counts,
        names='Cluster',
        values='Countries',
        hole=0.45,
        title="Country Distribution Across Clusters"
    )

    st.plotly_chart(fig, use_container_width=True)

