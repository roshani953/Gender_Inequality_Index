import streamlit as st
import pandas as pd
import numpy as np
import joblib
import plotly.express as px
import plotly.graph_objects as go

# --------------------------------------------------
# PAGE CONFIGURATION
# --------------------------------------------------

st.set_page_config(
    page_title="GII Country Clustering Dashboard",
    page_icon="🌍",
    layout="wide"
)

# --------------------------------------------------
# LOAD DATA AND MODELS
# --------------------------------------------------

@st.cache_data
def load_data():
    return pd.read_csv("GII_Final_Dataset.csv")

@st.cache_resource
def load_models():
    scaler = joblib.load("scaler.pkl")
    pca = joblib.load("pca.pkl")
    kmeans = joblib.load("kmeans_model.pkl")

    return scaler, pca, kmeans

df = load_data()
scaler, pca, kmeans = load_models()

# --------------------------------------------------
# FEATURE COLUMNS
# --------------------------------------------------

features = [
    'Human_development',
    'GII',
    'Maternal_mortality',
    'Adolescent_birth_rate',
    'Seats_parliament',
    'F_secondary_educ',
    'M_secondary_educ',
    'F_Labour_force',
    'M_Labour_force'
]

# Check required columns
required_columns = features + ['Country', 'Cluster']

if not all(col in df.columns for col in required_columns):
    st.error("Required columns are missing from the dataset.")
    st.stop()

# --------------------------------------------------
# SIDEBAR
# --------------------------------------------------

st.sidebar.title("🌍 GII Analytics")

st.sidebar.markdown(
    "Gender Inequality Analysis "
    "using Machine Learning"
)

page = st.sidebar.radio(
    "Navigation",
    [
        "Home",
        "Dataset Explorer",
        "EDA Dashboard",
        "Cluster Analysis",
        "Country Explorer",
        "Project Insights"
    ]
)

st.sidebar.markdown("---")
st.sidebar.caption("Machine Learning Model: K-Means")
st.sidebar.caption("Selected Clusters: 2")

